def generate_all(cve: dict[str, Any], base_dir: Path | None = None) -> dict[str, Path]:
    """Generate all four artifacts; returns their paths."""
    cve_id = str(cve.get("cve_id", "") or cve.get("cve-id", "") or "CVE-XXXX-YYYY")
    root = _cve_dir(cve_id, base=base_dir)
    root.mkdir(parents=True, exist_ok=True)

    artifacts = {
        "python": root / f"{cve_id}.py",
        "js": root / f"{cve_id}.js",
        "sh": root / f"{cve_id}.sh",
        "nuclei": root / f"{cve_id}.yaml",
    }

    artifacts["python"].write_text(generate_python_poc({**cve, "cve_id": cve_id}), encoding="utf-8")
    artifacts["js"].write_text(generate_js_poc({**cve, "cve_id": cve_id}), encoding="utf-8")
    # .sh uses the whitelisted suffix for the tool-command guard.
    sh_path = root / f"{cve_id}.nexus-poc.sh"
    sh_path.write_text(generate_sh_poc({**cve, "cve_id": cve_id}), encoding="utf-8")
    artifacts["sh"] = sh_path
    artifacts["nuclei"].write_text(
        generate_nuclei_template({**cve, "cve_id": cve_id}), encoding="utf-8"
    )
    return artifacts


def register_nuclei_template(yaml_path: Path, templates_dir: Path | None = None) -> Path:
    """Copy a generated nuclei template into templates/nuclei-custom/."""
    import shutil

    target_dir = templates_dir or (REPO_ROOT / "templates" / "nuclei-custom")
    target_dir.mkdir(parents=True, exist_ok=True)
    dest = target_dir / yaml_path.name
    shutil.copyfile(yaml_path, dest)
    return dest
